"""Independent adversarial fixtures for the publication scanner (no real secrets)."""
import contextlib
import hashlib
import importlib.util
import io
import json
import subprocess
import tempfile
import unittest
from pathlib import Path

SPEC = importlib.util.spec_from_file_location("release_audit", Path(__file__).resolve().parents[1] / "scripts/audit_release.py")
audit = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(audit)


class ReleaseScanTests(unittest.TestCase):
    def test_credential_families_and_no_values_returned(self):
        cases = ["gh" + "p_" + "a" * 35, "github_" + "pat_" + "a" * 70,
                 "gh" + "u_" + "b" * 35, "sk-" + "proj-" + "x" * 40]
        for secret in cases:
            with self.subTest(prefix=secret[:3]):
                result = audit.scan_text(secret, "fixture")
                self.assertIn("recognizable_token", [x["reason"] for x in result])
                self.assertNotIn(secret, json.dumps(result))

    def test_project_name_is_not_a_token(self):
        self.assertEqual(audit.scan_text("risk-decision-lab-auto-resume", "fixture"), [])

    def test_internal_urls_with_port_end_and_query(self):
        for host in ["corp", "internal"]:
            for ending in [":443/route", ":8080", "?q=1", "/route", ""]:
                result = audit.scan_text("https://test." + host + ending, "fixture")
                self.assertIn("internal_link", [x["reason"] for x in result])
        self.assertEqual(audit.scan_text("https://example.corporate.com/", "fixture"), [])

    def test_local_paths_and_explicit_credentials(self):
        for text, expected in [("/Users/" + "fixture/file", "personal_absolute_path"),
                               ("/private/" + "tmp/fixture/file", "temporary_absolute_path"),
                               ("/tmp/" + "fixture/file", "temporary_absolute_path"),
                               ("/private/var/" + "folders/test/file", "temporary_absolute_path"),
                               ("EXAMPLE_PASS" + "WORD=synthetic-only", "credential_assignment"),
                               ('{"api_' + 'key": "synthetic-only"}', "credential_assignment")]:
            self.assertIn(expected, [x["reason"] for x in audit.scan_text(text, "fixture")])

    def test_binary_requires_explicit_hash_bound_provenance(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); blob = b"\x89PNG\r\n\x1a\nfixture"
            (root / "generated.png").write_bytes(blob)
            receipt = audit.audit(root)
            self.assertEqual(receipt["findings"], [])
            self.assertFalse(receipt["release_ready"])
            self.assertEqual(receipt["status"], "MANUAL_REVIEW_REQUIRED")
            claim = {"sha256": hashlib.sha256(blob).hexdigest(), "provenance": "fixture generated by this test", "reviewer": "fixture-reviewer"}
            receipt = audit.audit(root, {"generated.png": claim})
            self.assertTrue(receipt["release_ready"])
            (root / "generated.png").write_bytes(blob + b"changed")
            self.assertFalse(audit.audit(root, {"generated.png": claim})["release_ready"])

    def test_unknown_binary_and_empty_review_are_not_implicitly_safe(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); (root / "asset.unknown").write_bytes(b"\xff\x00")
            receipt = audit.audit(root, {"asset.unknown": {"sha256": hashlib.sha256(b"\xff\x00").hexdigest(), "provenance": "", "reviewer": ""}})
            self.assertEqual(len(receipt["binary_review_required"]), 1)
            self.assertFalse(receipt["release_ready"])

    def test_symlink_and_private_directory_scope(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); (root / "real.txt").write_text("safe")
            (root / "link.txt").symlink_to(root / "real.txt")
            (root / ".lab-run").mkdir(); (root / ".lab-run/private.txt").write_text("gh" + "p_" + "a" * 35)
            receipt = audit.audit(root)
            self.assertEqual(receipt["findings"], [{"file": "link.txt", "reason": "symlink_requires_removal"}])
            self.assertFalse(receipt["release_ready"])

    def test_cli_root_and_failure_redaction(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); (root / "safe.txt").write_text("safe")
            output = io.StringIO()
            with contextlib.redirect_stdout(output):
                result = audit.main(["--root", str(root)])
            self.assertEqual(result, 0); self.assertTrue(json.loads(output.getvalue())["release_ready"])
            (root / "invalid.json").write_text("invalid")
            output = io.StringIO()
            with contextlib.redirect_stdout(output):
                result = audit.main(["--root", str(root), "--binary-review", str(root / "invalid.json")])
            self.assertEqual(result, 1)
            self.assertNotIn(str(root), output.getvalue())
            self.assertEqual(json.loads(output.getvalue())["status"], "AUDIT_FAILED")

    def test_reachable_history_including_deleted_files_and_symlink(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            def git(*args):
                return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=True).stdout.strip()
            git("init", "-q"); git("config", "user.name", "Fixture Reviewer"); git("config", "user.email", "fixture@example.invalid")
            secret = "github_" + "pat_" + "x" * 70
            (root / "deleted.txt").write_text(secret)
            (root / "past-link").symlink_to("deleted.txt")
            git("add", "."); git("commit", "-qm", "fixture initial")
            old_commit = git("rev-parse", "HEAD")
            git("rm", "deleted.txt", "past-link"); git("commit", "-qm", "fixture removal")
            receipt = audit.audit(root)
            self.assertEqual(receipt["git_commits_checked"], 2)
            self.assertIn({"file": "history:" + old_commit + ":deleted.txt", "reason": "recognizable_token"}, receipt["findings"])
            self.assertIn({"file": "history:" + old_commit + ":past-link", "reason": "symlink_requires_removal"}, receipt["findings"])
            self.assertNotIn(secret, json.dumps(receipt))
